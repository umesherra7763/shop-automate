// To add another language: copy one of the blocks above, translate, and add it here.
export const LANGS: Record<string, { label: string; dict: Partial<Record<Key, string>> }> = {
  te: { label: "తెలుగు (Telugu)", dict: te },
  hi: { label: "हिन्दी (Hindi)", dict: hi },
};

export const DEFAULT_LANG = "te";

export const getSettings = cache(async (): Promise<Record<string, string>> => {
  const rows = await db.setting.findMany();
  return Object.fromEntries(rows.map((r) => [r.key, r.value]));
});

export type T = (k: Key) => string;

// Returns a label function: "English / Local" when a second language is chosen in Settings.
export async function getT(): Promise<T> {
  const s = await getSettings();
  const d = LANGS[s.lang ?? DEFAULT_LANG]?.dict; // "" in Settings means English only
  return (k) => (d?.[k] ? `${en[k]} / ${d[k]}` : en[k]);
}
